// Bundles src/ into the single file HACS and Home Assistant load: ./aqara-feeder-card.js
//   npm run build   — build once
//   npm run watch   — rebuild on change
//   npm run check   — fail if the committed bundle is out of date (used in CI)
import * as esbuild from 'esbuild';
import fs from 'node:fs';

const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const OUTFILE = 'aqara-feeder-card.js';
const mode = process.argv[2];

const options = {
  entryPoints: ['src/index.js'],
  bundle: true,
  format: 'iife',
  target: 'es2017',
  charset: 'utf8',
  legalComments: 'none',
  define: { __VERSION__: JSON.stringify(pkg.version) },
  banner: { js: `/*! Aqara Feeder Card v${pkg.version} | MIT | built from src/ — do not edit this file directly */` },
};

if (mode === '--watch') {
  const ctx = await esbuild.context({ ...options, outfile: OUTFILE, logLevel: 'info' });
  await ctx.watch();
} else if (mode === '--check') {
  const result = await esbuild.build({ ...options, write: false, outfile: OUTFILE });
  const fresh = result.outputFiles[0].text;
  const committed = fs.existsSync(OUTFILE) ? fs.readFileSync(OUTFILE, 'utf8') : '';
  if (fresh !== committed) {
    console.error(`${OUTFILE} is out of date. Run "npm run build" and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUTFILE} is up to date.`);
} else {
  await esbuild.build({ ...options, outfile: OUTFILE, logLevel: 'info' });
}
